"""Generates pkg/environment/signatures_table.go: the Python signature of
every builtin filter and test in the pinned Jinja2, used by gojinja to
raise where Jinja2 raises TypeError on a wrong call. Run via
`make signatures`; `make parity` fails when the file is stale."""

import inspect

from jinja2 import Environment
from jinja2.utils import _PassArg

# C builtins whose TypeError wording differs from Python functions.
STYLES = {
    "abs": "styleCOneArg",
    "len": "styleCOneArg",
    "callable": "styleCOneArg",
    "eq": "styleOperator",
    "ne": "styleOperator",
    "lt": "styleOperator",
    "le": "styleOperator",
    "gt": "styleOperator",
    "ge": "styleOperator",
}


def row(name, fn):
    target = inspect.unwrap(fn)
    params = list(inspect.signature(target).parameters.values())
    pos = [p for p in params if p.kind in (p.POSITIONAL_ONLY, p.POSITIONAL_OR_KEYWORD)]
    required = 0
    for p in pos:
        if p.default is not p.empty:
            break
        required += 1
    fields = [
        f'fn: "{target.__name__}"',
        "params: []string{%s}" % ", ".join(f'"{p.name}"' for p in pos),
    ]
    if required:
        fields.append(f"required: {required}")
    posonly = sum(1 for p in params if p.kind == p.POSITIONAL_ONLY)
    if posonly:
        fields.append(f"posOnly: {posonly}")
    if _PassArg.from_obj(target) is not None:
        fields.append("hidden: true")
    if any(p.kind == p.VAR_POSITIONAL for p in params):
        fields.append("varargs: true")
    if any(p.kind == p.VAR_KEYWORD for p in params):
        fields.append("varkw: true")
    if target.__name__ in STYLES:
        fields.append("style: " + STYLES[target.__name__])
    return f'\t"{name}": {{{", ".join(fields)}}},'


def main():
    env = Environment()
    print("// Code generated by tools/parity/signatures.py from the Jinja2 pinned in")
    print("// tools/parity/requirements.txt. DO NOT EDIT; run `make signatures`.")
    print()
    print("package environment")
    for var, table in (("builtinFilterSignatures", env.filters), ("builtinTestSignatures", env.tests)):
        print()
        print(f"var {var} = map[string]*signature{{")
        for name in sorted(table):
            print(row(name, table[name]))
        print("}")


if __name__ == "__main__":
    main()
