"""Generates pkg/environment/codectables_table.go: Python's single-byte
codec tables and its codec name aliases, taken from the Python that runs
the pinned Jinja2. Run via `make codectables`; `make parity` fails when
the file is stale."""

import codecs
import importlib
import pkgutil
import sys

import encodings
import encodings.aliases

UNDEFINED = "￾"

# Codecs implemented in Go code rather than by table.
CODED = [
    "ascii", "latin_1", "utf_8", "utf_8_sig", "utf_16", "utf_16_le", "utf_16_be",
    "utf_32", "utf_32_le", "utf_32_be", "utf_7", "unicode_escape", "raw_unicode_escape",
    "punycode", "charmap", "undefined",
    # Table-driven CJK codecs (tools/parity/cjktables.py).
    "big5", "big5hkscs", "cp932", "cp949", "cp950", "euc_jis_2004", "euc_jisx0213",
    "euc_jp", "euc_kr", "gb18030", "gb2312", "gbk", "johab", "shift_jis",
    "shift_jis_2004", "shift_jisx0213",
]


def single_byte_codecs():
    out = []
    for m in sorted(m.name for m in pkgutil.iter_modules(encodings.__path__)):
        try:
            mod = importlib.import_module("encodings." + m)
        except ImportError:
            continue
        if hasattr(mod, "decoding_table") or hasattr(mod, "decoding_map"):
            out.append(m)
    return out


def go_rune(c):
    return f"0x{ord(c):04x}"


def main():
    tables = single_byte_codecs()
    supported = set(tables) | set(CODED)
    print("// Code generated by tools/parity/codectables.py from the Python running the")
    print("// Jinja2 pinned in tools/parity/requirements.txt. DO NOT EDIT; run `make codectables`.")
    print()
    print("package environment")
    print()
    print("// charmapTables maps each single-byte codec to its 256 decoded")
    print("// characters (0xfffe where the byte is undefined) and to the")
    print("// characters whose encoding is not the lowest byte decoding to them")
    print("// (-1 when they cannot be encoded).")
    print("var charmapTables = map[string]charmapTable{")
    for name in tables:
        decoded = []
        for b in range(256):
            try:
                c = bytes([b]).decode(name)
                assert len(c) == 1 and c != UNDEFINED
            except UnicodeDecodeError:
                c = UNDEFINED
            decoded.append(c)
        inverse = {}
        for b, c in enumerate(decoded):
            if c != UNDEFINED:
                inverse.setdefault(c, b)
        overrides = []
        for c, b in sorted(inverse.items()):
            try:
                e = c.encode(name)
                actual = e[0]
                assert len(e) == 1
            except UnicodeEncodeError:
                actual = -1
            if actual != b:
                overrides.append((c, actual))
        print(f'\t"{name}": {{')
        print("\t\tdecode: [256]rune{")
        for i in range(0, 256, 8):
            print("\t\t\t" + ", ".join(go_rune(c) for c in decoded[i:i + 8]) + ",")
        print("\t\t},")
        if overrides:
            print("\t\tencode: map[rune]int{" + ", ".join(f"{go_rune(c)}: {b}" for c, b in overrides) + "},")
        print("\t},")
    print("}")
    print()
    modules = sorted(m.name for m in pkgutil.iter_modules(encodings.__path__))
    nontext = []
    for m in modules:
        try:
            info = codecs.lookup(m)
        except LookupError:
            continue
        if not getattr(info, "_is_text_encoding", True):
            nontext.append(m)
    print("// codecModules are the codec modules encodings.search_function can")
    print("// import: true for text codecs gojinja implements, false for codecs")
    print("// that are not text encodings (base64, zlib, ...).")
    print("var codecModules = map[string]bool{")
    for m in sorted(supported):
        print(f'\t"{m}": true,')
    for m in nontext:
        print(f'\t"{m}": false,')
    print("}")
    print()
    print("// codecAliases is encodings.aliases.aliases for those modules.")
    print("var codecAliases = map[string]string{")
    for alias, module in sorted(encodings.aliases.aliases.items()):
        if module in supported or module in nontext:
            print(f'\t"{alias}": "{module}",')
    print("}")


if __name__ == "__main__":
    sys.exit(main())
