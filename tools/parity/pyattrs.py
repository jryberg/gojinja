"""Generates pkg/environment/pyattrs_table.go: the attributes starting with
an underscore that Python's objects have, per type, taken from the Python
that runs the pinned Jinja2. The sandbox turns such an attribute, when it
exists, into an Undefined that raises SecurityError on use; one that does
not exist is looked up as an item, or is a plain Undefined, as in Python.
Run via `make pyattrs`; `make parity` fails when the file is stale."""

import markupsafe
from jinja2 import Environment
from jinja2.runtime import BlockReference, ChainableUndefined, DebugUndefined, LoopContext, StrictUndefined, TemplateReference, Undefined
from jinja2.utils import Cycler, Joiner, Namespace


class UserObject:
    pass


env = Environment()
macro = env.from_string("{% macro m() %}{% endmacro %}").module.m

OBJECTS = {
    "NoneType": None,
    "bool": True,
    "int": 1,
    "float": 1.0,
    "complex": 1j,
    "str": "a",
    "Markup": markupsafe.Markup("a"),
    "bytes": b"a",
    "list": [],
    "tuple": (),
    "dict": {},
    "range": range(1),
    "dict_keys": {}.keys(),
    "dict_values": {}.values(),
    "dict_items": {}.items(),
    "generator": (x for x in []),
    "list_reverseiterator": reversed([]),
    "reversed": reversed(()),
    "range_iterator": reversed(range(1)),
    "dict_reversekeyiterator": reversed({}),
    "dict_reversevalueiterator": reversed({}.values()),
    "dict_reverseitemiterator": reversed({}.items()),
    "dict_itemiterator": iter({}.items()),
    "builtin_function_or_method": [].append,
    "method": markupsafe.Markup("a").upper,
    "function": lambda: None,
    "Namespace": Namespace(),
    "Cycler": Cycler(1),
    "Joiner": Joiner(),
    "LoopContext": LoopContext([], Undefined),
    "Undefined": Undefined(),
    "ChainableUndefined": ChainableUndefined(),
    "DebugUndefined": DebugUndefined(),
    "StrictUndefined": StrictUndefined(),
    "Macro": macro,
    "BlockReference": BlockReference("b", None, [], 0),
    "TemplateReference": TemplateReference(None),
    # The caller's own Go values, as instances of a Python class.
    "object": UserObject(),
    # Classes, by qualified name.
    "type:dict": dict,
    "type:range": range,
    "type:jinja2.utils.Cycler": Cycler,
    "type:jinja2.utils.Joiner": Joiner,
    "type:jinja2.utils.Namespace": Namespace,
}

print("// Code generated by tools/parity/pyattrs.py; DO NOT EDIT.\n")
print("package environment\n")
print("// pyPrivateAttrs holds, per Python type name, the attributes starting")
print("// with an underscore that an object of that type has. A class is")
print('// \"type:\" and its qualified name; \"object\" is any other object.')
print("var pyPrivateAttrs = map[string]map[string]bool{")
for name, obj in OBJECTS.items():
    attrs = sorted(a for a in dir(obj) if a.startswith("_"))
    print(f"\t{name!r}: {{".replace("'", '"'))
    for a in attrs:
        print(f'\t\t"{a}": true,')
    print("\t},")
print("}")
