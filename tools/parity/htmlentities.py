"""Generates pkg/escape/html5_table.go: the data behind Python's
html.unescape, which markupsafe's Markup.unescape and striptags use — the
HTML5 named character references, the numeric references remapped as
invalid, and the code points they drop — taken from the Python that runs
the pinned Jinja2. Run via `make htmlentities`; `make parity` fails when
the file is stale."""

import html
import html.entities


def go_string(s):
    return '"' + "".join(f"\\U{ord(c):08x}" if ord(c) > 0xFFFF else f"\\u{ord(c):04x}" if not (0x20 <= ord(c) < 0x7F) or c in '"\\' else c for c in s) + '"'


print("// Code generated by tools/parity/htmlentities.py; DO NOT EDIT.\n")
print("package escape\n")
print("// html5Entities is html.entities.html5: each named character reference,")
print("// with its semicolon or, for the legacy ones, without, and its text.")
print("var html5Entities = map[string]string{")
for name, text in sorted(html.entities.html5.items()):
    print(f"\t{go_string(name)}: {go_string(text)},")
print("}\n")
print("// invalidCharrefs is html._invalid_charrefs: the numeric references")
print("// html.unescape replaces instead of decoding.")
print("var invalidCharrefs = map[int64]string{")
for num, text in sorted(html._invalid_charrefs.items()):
    print(f"\t{num:#x}: {go_string(text)},")
print("}\n")
print("// invalidCodepoints is html._invalid_codepoints: the code points a")
print("// numeric reference to decodes to nothing.")
print("var invalidCodepoints = map[int64]bool{")
for num in sorted(html._invalid_codepoints):
    print(f"\t{num:#x}: true,")
print("}")
