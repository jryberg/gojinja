"""Generates internal/pyunicode/pyunicode_table.go: every piece of Unicode
data that template-visible behaviour depends on, taken from the Python
that runs the pinned Jinja2. Run via `make pyunicode`; `make parity`
fails when the file is stale.

Everything is probed through Python's own str methods and re module rather
than read from unicodedata, so the tables say what Python does, and Go's
unicode package (whose Unicode version follows the Go toolchain) is never
consulted."""

import re
import sys
import unicodedata

from jinja2._identifier import pattern as jinja_name_re

CHARS = [chr(c) for c in range(0x110000) if not 0xD800 <= c < 0xE000]
LETTERS = "abcdefghijklmnopqrstuvwxyz"


def ranges(pred):
    out = []
    start = prev = None
    for ch in CHARS:
        c = ord(ch)
        if pred(ch):
            if start is None:
                start = c
            elif c != prev + 1:
                out.append((start, prev))
                start = c
            prev = c
        elif start is not None:
            out.append((start, prev))
            start = None
    if start is not None:
        out.append((start, prev))
    return out


def members(rs):
    return {chr(c) for lo, hi in rs for c in range(lo, hi + 1)}


def go_string(s):
    return '"' + "".join(f"\\U{ord(c):08x}" if ord(c) > 0xFFFF else f"\\u{ord(c):04x}" for c in s) + '"'


def emit_set(name, doc, rs):
    print(f"// {doc}")
    print(f"var {name} = Set{{")
    for lo, hi in rs:
        print(f"\t{{0x{lo:04x}, 0x{hi:04x}}},")
    print("}")
    print()


def emit_mapping(name, doc, pairs):
    print(f"// {doc}")
    print(f"var {name} = mapping{{")
    for c, s in pairs:
        print(f"\t{{0x{ord(c):04x}, {go_string(s)}}},")
    print("}")
    print()


def is_cased(ch):
    return ch.islower() or ch.isupper() or (ch.istitle() and not ch.isupper())


def is_case_ignorable(ch):
    # Final sigma skips case-ignorable characters on both sides. Before a
    # sigma, an ignorable character is skipped (so a cased one before it
    # counts, and a cased ignorable one itself does not); any other
    # character ends the search.
    if is_cased(ch):
        return (ch + "Σ").lower().endswith("σ")
    return ("a" + ch + "Σ").lower().endswith("ς")


def main():
    lower = ranges(str.islower)
    upper = ranges(str.isupper)
    title = ranges(lambda c: c.istitle() and not c.isupper())
    space = ranges(str.isspace)
    word = ranges(lambda c: re.fullmatch(r"\w", c) is not None)
    decimal = ranges(str.isdecimal)
    for ch in CHARS:
        # A single character's islower/isupper are the Lowercase and
        # Uppercase properties; no character has both.
        assert not (ch.islower() and ch.isupper()), ch
        # re's \d, \s and \w are str.isdecimal, str.isspace and isalnum.
        assert (re.fullmatch(r"\d", ch) is not None) == ch.isdecimal(), ch
        assert (re.fullmatch(r"\s", ch) is not None) == ch.isspace(), ch
        assert (re.fullmatch(r"\w", ch) is not None) == (ch.isalnum() or ch == "_"), ch
    # Decimal digits come in runs of ten, each starting at zero, so a
    # digit's value is its distance from the start of its run, mod 10.
    for lo, hi in decimal:
        assert (hi - lo + 1) % 10 == 0, (lo, hi)
        for c in range(lo, hi + 1):
            assert unicodedata.decimal(chr(c)) == (c - lo) % 10, c

    # Under re.IGNORECASE an ASCII letter also matches the characters
    # listed here. Every class urlize uses with IGNORECASE is its plain
    # class plus these letters, which the asserts below confirm.
    fold = {L: [c for c in CHARS if c not in (L, L.upper()) and re.fullmatch(L, c, re.I)] for L in LETTERS}

    def folded(chars):
        return set(chars) | {c.upper() for c in chars if c.isalpha()} | {f for c in chars for f in fold.get(c, [])}

    word_chars, dec_chars, space_chars = members(word), members(decimal), members(space)
    expect = {
        r"[\w%-]": word_chars | {"%", "-"},
        r"[\w%]": word_chars | {"%"},
        r"[a-z]": folded(LETTERS),
        r"[\d]": dec_chars,
        r"[\da-f]": dec_chars | folded("abcdef"),
        r"\S": set(CHARS) - space_chars,
    }
    for atom, want in expect.items():
        got = {c for c in CHARS if re.fullmatch(atom, c, re.I)}
        assert got == want, (atom, sorted(got ^ want)[:10])
    for L in LETTERS:
        got = {c for c in CHARS if re.fullmatch(L, c, re.I)}
        assert got == folded(L), L

    print("// Code generated by tools/parity/pyunicode.py from the Python running the")
    print("// Jinja2 pinned in tools/parity/requirements.txt (Unicode "
          f"{unicodedata.unidata_version}). DO NOT EDIT; run `make pyunicode`.")
    print()
    print("package pyunicode")
    print()
    emit_set("lowerSet", "lowerSet is the Lowercase property, behind str.islower.", lower)
    emit_set("upperSet", "upperSet is the Uppercase property, behind str.isupper.", upper)
    emit_set("titleSet", "titleSet is the titlecase letters (Lt), behind str.istitle.", title)
    emit_set("caseIgnorableSet", "caseIgnorableSet is what str.lower's final-sigma rule skips.",
             ranges(is_case_ignorable))
    emit_set("alphaSet", "alphaSet is str.isalpha.", ranges(str.isalpha))
    emit_set("alnumSet", "alnumSet is str.isalnum.", ranges(str.isalnum))
    emit_set("decimalSet", "decimalSet is str.isdecimal and the regex class \\d.", decimal)
    emit_set("digitSet", "digitSet is str.isdigit.", ranges(str.isdigit))
    emit_set("numericSet", "numericSet is str.isnumeric.", ranges(str.isnumeric))
    emit_set("spaceSet", "spaceSet is str.isspace and the regex class \\s.", space)
    emit_set("printableSet", "printableSet is str.isprintable.", ranges(str.isprintable))
    emit_set("wordSet", "wordSet is the regex class \\w.", word)
    emit_set("xidStartSet", "xidStartSet is what str.isidentifier accepts first.",
             ranges(str.isidentifier))
    emit_set("xidContinueSet", "xidContinueSet is what str.isidentifier accepts after the first.",
             ranges(lambda c: ("a" + c).isidentifier()))
    emit_set("jinjaNameSet", "jinjaNameSet is the characters of Jinja2's name token (jinja2._identifier).",
             ranges(lambda c: jinja_name_re.fullmatch(c) is not None))
    emit_mapping("upperMap", "upperMap is str.upper for the characters it changes.",
                 [(c, c.upper()) for c in CHARS if c.upper() != c])
    emit_mapping("lowerMap", "lowerMap is str.lower, without the final-sigma rule, for the characters it changes.",
                 [(c, c.lower()) for c in CHARS if c.lower() != c])
    emit_mapping("titleMap", "titleMap is str.title of one character, for the characters it changes.",
                 [(c, c.title()) for c in CHARS if c.title() != c])
    emit_mapping("foldMap", "foldMap is str.casefold for the characters it changes.",
                 [(c, c.casefold()) for c in CHARS if c.casefold() != c])
    print("// ignoreCaseFold lists, for each ASCII letter, the other characters it")
    print("// matches under re.IGNORECASE besides its own two cases.")
    print("var ignoreCaseFold = [26][]rune{")
    for L in LETTERS:
        print(f"\t{{{', '.join(f'0x{ord(c):04x}' for c in fold[L])}}},")
    print("}")


if __name__ == "__main__":
    sys.exit(main())
