"""Generates pkg/environment/lipsum_table.go: the words of Jinja2's
LOREM_IPSUM_WORDS, which the lipsum global draws from, taken from the
pinned Jinja2. Run via `make lipsum`; `make parity` fails when the file
is stale."""

from jinja2.constants import LOREM_IPSUM_WORDS

print("// Code generated by tools/parity/lipsum.py; DO NOT EDIT.\n")
print("package environment\n")
print("// lipsumWords is jinja2.constants.LOREM_IPSUM_WORDS split into words.")
print("var lipsumWords = []string{")
words = LOREM_IPSUM_WORDS.split()
for i in range(0, len(words), 8):
    print("\t" + " ".join(f'"{w}",' for w in words[i:i + 8]))
print("}")
