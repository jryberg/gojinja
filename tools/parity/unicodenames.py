"""Generates internal/unicodename/names_table.go: Unicode character names
and name aliases as the Python that runs the pinned Jinja2 resolves them
(unicodedata.name / \\N{...}). Run via `make unicodenames`; `make parity`
fails when the file is stale.

Name aliases are read from the vendored Unicode NameAliases file matching
Python's Unicode version, and each is checked against unicodedata.lookup."""

import os
import re
import sys
import unicodedata

ALIASES = os.path.join(os.path.dirname(__file__), "data", f"NameAliases-{unicodedata.unidata_version}.txt")


def lookup_ok(name, cp):
    try:
        return unicodedata.lookup(name) == chr(cp)
    except KeyError:
        return False


def main():
    names = {}
    for cp in range(0x110000):
        n = unicodedata.name(chr(cp), None)
        if n:
            names[cp] = n
    # Runs of PREFIX-HEX names become ranges. Python computes some of them
    # (lookup is then case-sensitive and accepts 4 or 5 hex digits); the
    # others are plain stored names.
    ranges = []
    explicit = {}
    for cp, n in sorted(names.items()):
        m = re.fullmatch(r"(.*-)([0-9A-F]{4,6})", n)
        if m and int(m.group(2), 16) == cp and f"{cp:04X}" == m.group(2):
            prefix = m.group(1)
            computed = not lookup_ok(n.lower(), cp)
            if ranges and ranges[-1][0] == prefix and ranges[-1][2] == cp - 1 and ranges[-1][3] == computed:
                ranges[-1][2] = cp
                continue
            ranges.append([prefix, cp, cp, computed])
            continue
        if not n.startswith("HANGUL SYLLABLE "):
            explicit[cp] = n
    # Single-character "ranges" are just names.
    for r in [r for r in ranges if r[1] == r[2] and not r[3]]:
        explicit[r[1]] = names[r[1]]
        ranges.remove(r)
    aliases = []
    for line in open(ALIASES, encoding="utf-8"):
        line = line.split("#")[0].strip()
        if not line:
            continue
        cp, name, _ = line.split(";")
        assert lookup_ok(name, int(cp, 16)), name
        aliases.append((name, int(cp, 16)))
    print("// Code generated by tools/parity/unicodenames.py from the Python running the")
    print("// Jinja2 pinned in tools/parity/requirements.txt (Unicode "
          f"{unicodedata.unidata_version}). DO NOT EDIT; run `make unicodenames`.")
    print()
    print("package unicodename")
    print()
    print("// nameRanges are runs of characters named PREFIX-HEX.")
    print("var nameRanges = []nameRange{")
    for prefix, lo, hi, computed in ranges:
        print(f'\t{{"{prefix}", 0x{lo:04x}, 0x{hi:04x}, {str(computed).lower()}}},')
    print("}")
    print()
    cps = sorted(explicit)
    print("// namedRunes and nameList hold every other name (Hangul syllables are")
    print("// computed), in code point order; nameList is newline-separated.")
    print("var namedRunes = []rune{")
    for i in range(0, len(cps), 12):
        print("\t" + ", ".join(f"0x{c:04x}" for c in cps[i:i + 12]) + ",")
    print("}")
    print()
    assert not any("`" in n for n in explicit.values())
    print("const nameList = `" + "\n".join(explicit[c] for c in cps) + "`")
    print()
    print("// aliases are the formal name aliases \\N{...} accepts.")
    print("var aliases = map[string]rune{")
    for name, cp in aliases:
        print(f'\t"{name}": 0x{cp:04x},')
    print("}")


if __name__ == "__main__":
    sys.exit(main())
