"""Generates pkg/environment/strtables_table.go: the Unicode data Python's
str methods use beyond Go's unicode package (full case mappings, case
folding, numeric types, identifier and case-ignorable characters), taken
from the Python that runs the pinned Jinja2. Run via `make strtables`;
`make parity` fails when the file is stale.

Go and this Python must share a Unicode version: single-character case
mappings come from Go's unicode package and only multi-character ones are
tabulated here."""

import sys
import unicodedata

CHARS = [chr(c) for c in range(0x110000) if not 0xD800 <= c < 0xE000]


def ranges(pred):
    out = []
    start = prev = None
    for ch in CHARS:
        c = ord(ch)
        if pred(ch):
            if start is None:
                start = c
            elif c != prev + 1:
                out.append((start, prev))
                start = c
            prev = c
    if start is not None:
        out.append((start, prev))
    return out


def go_string(s):
    return '"' + "".join(f"\\U{ord(c):08x}" if ord(c) > 0xFFFF else f"\\u{ord(c):04x}" for c in s) + '"'


def emit_map(name, doc, pairs):
    print(f"// {doc}")
    print(f"var {name} = map[rune]string{{")
    for c, s in pairs:
        print(f"\t0x{ord(c):04x}: {go_string(s)},")
    print("}")
    print()


def emit_ranges(name, doc, rs):
    print(f"// {doc}")
    print(f"var {name} = []runeRange{{")
    for lo, hi in rs:
        print(f"\t{{0x{lo:04x}, 0x{hi:04x}}},")
    print("}")
    print()


def is_case_ignorable(ch):
    # Final sigma skips case-ignorable characters on both sides: a
    # character is ignorable when sigma after it still sees the cased 'A'
    # before it, but not the uncased space.
    if ch.lower() != ch or ch.upper() != ch:
        return False
    return ("A" + ch + "Σ").lower().endswith("ς") and not (" " + ch + "Σ").lower().endswith("ς")


def main():
    for ch in CHARS:
        assert ch.isdecimal() == (unicodedata.category(ch) == "Nd"), ch
    print("// Code generated by tools/parity/strtables.py from the Python running the")
    print("// Jinja2 pinned in tools/parity/requirements.txt (Unicode "
          f"{unicodedata.unidata_version}). DO NOT EDIT; run `make strtables`.")
    print()
    print("package environment")
    print()
    print(f'const pyUnicodeVersion = "{unicodedata.unidata_version}"')
    print()
    emit_map("upperFull", "upperFull holds str.upper results longer than one character.",
             [(c, c.upper()) for c in CHARS if len(c.upper()) > 1])
    emit_map("lowerFull", "lowerFull holds str.lower results longer than one character.",
             [(c, c.lower()) for c in CHARS if len(c.lower()) > 1])
    emit_map("titleFull", "titleFull holds str.title results longer than one character.",
             [(c, c.title()) for c in CHARS if len(c.title()) > 1])
    emit_map("casefoldFull", "casefoldFull holds str.casefold results that differ from str.lower.",
             [(c, c.casefold()) for c in CHARS if c.casefold() != c.lower()])
    emit_ranges("digitExtra", "digitExtra are str.isdigit characters that are not decimal (Nd).",
                ranges(lambda c: c.isdigit() and not c.isdecimal()))
    emit_ranges("numericExtra", "numericExtra are str.isnumeric characters outside the N categories.",
                ranges(lambda c: c.isnumeric() and unicodedata.category(c)[0] != "N"))
    emit_ranges("numericMissing", "numericMissing are N-category characters that are not str.isnumeric.",
                ranges(lambda c: not c.isnumeric() and unicodedata.category(c)[0] == "N"))
    emit_ranges("xidStart", "xidStart are the characters str.isidentifier accepts first.",
                ranges(lambda c: c.isidentifier()))
    emit_ranges("xidContinue", "xidContinue are the characters str.isidentifier accepts after the first.",
                ranges(lambda c: ("a" + c).isidentifier()))
    emit_ranges("caseIgnorable", "caseIgnorable are the characters final-sigma handling skips.",
                ranges(is_case_ignorable))


if __name__ == "__main__":
    sys.exit(main())
