"""Generates pkg/environment/idnatables_table.go: the data Python's idna
codec (encodings/idna.py, IDNA2003) uses, taken from the Python that runs
the pinned Jinja2. Run via `make idnatables`; `make parity` fails when the
file is stale.

Nameprep's stringprep tables (RFC 3454) are probed from the stringprep
module. Its NFKC is unicodedata.ucd_3_2_0.normalize, which CPython runs as
a full decomposition with Unicode 3.2 data (characters unassigned in 3.2
stay as they are) followed by canonical reordering and composition with
the current database's combining classes and composition pairs; those
three tables are emitted for pkg/environment's port of that algorithm."""

import stringprep
import sys
import unicodedata
from unicodedata import ucd_3_2_0

CHARS = [chr(c) for c in range(0x110000) if not 0xD800 <= c < 0xE000]
HANGUL = range(0xAC00, 0xAC00 + 11172)


def ranges(pred):
    out = []
    start = prev = None
    for ch in CHARS:
        c = ord(ch)
        if pred(ch):
            if start is None:
                start = c
            elif c != prev + 1:
                out.append((start, prev))
                start = c
            prev = c
    if start is not None:
        out.append((start, prev))
    return out


def go_string(s):
    return '"' + "".join(f"\\U{ord(c):08x}" if ord(c) > 0xFFFF else f"\\u{ord(c):04x}" for c in s) + '"'


def emit_ranges(name, doc, rs):
    print(f"// {doc}")
    print(f"var {name} = pyunicode.Set{{")
    for lo, hi in rs:
        print(f"\t{{Lo: 0x{lo:04x}, Hi: 0x{hi:04x}}},")
    print("}")
    print()


def emit_map(name, doc, pairs):
    print(f"// {doc}")
    print(f"var {name} = map[rune]string{{")
    for c, s in pairs:
        print(f"\t0x{ord(c):04x}: {go_string(s)},")
    print("}")
    print()


def prohibited(ch):
    return any(f(ch) for f in (
        stringprep.in_table_c12, stringprep.in_table_c22, stringprep.in_table_c3,
        stringprep.in_table_c4, stringprep.in_table_c5, stringprep.in_table_c6,
        stringprep.in_table_c7, stringprep.in_table_c8, stringprep.in_table_c9))


def hangul_decomposition(c):
    s = c - 0xAC00
    out = chr(0x1100 + s // 588) + chr(0x1161 + s % 588 // 28)
    if s % 28:
        out += chr(0x11A7 + s % 28)
    return out


def composition_pairs():
    # CPython's makeunicodedata.py: canonical two-character decompositions
    # whose first character is a starter, minus composition exclusions,
    # which are exactly the composites NFC does not preserve.
    pairs = []
    for ch in CHARS:
        d = unicodedata.decomposition(ch)
        if not d or d.startswith("<"):
            continue
        parts = d.split()
        if len(parts) != 2:
            continue
        a, b = (chr(int(p, 16)) for p in parts)
        if unicodedata.combining(a) == 0 and unicodedata.normalize("NFC", ch) == ch:
            pairs.append((a, b, ch))
    return pairs


def main():
    for c in HANGUL:
        assert ucd_3_2_0.normalize("NFKD", chr(c)) == hangul_decomposition(c)
    print("// Code generated by tools/parity/idnatables.py from the Python running the")
    print("// Jinja2 pinned in tools/parity/requirements.txt (Unicode "
          f"{unicodedata.unidata_version}). DO NOT EDIT; run `make idnatables`.")
    print()
    print("package environment")
    print()
    print('import "github.com/jryberg/gojinja/internal/pyunicode"')
    print()
    emit_ranges("nameprepB1", "nameprepB1 is stringprep table B.1, characters mapped to nothing.",
                ranges(stringprep.in_table_b1))
    emit_map("nameprepB2", "nameprepB2 is stringprep's map_table_b2, case folding for NFKC.",
             [(ch, stringprep.map_table_b2(ch)) for ch in CHARS if stringprep.map_table_b2(ch) != ch])
    emit_ranges("nameprepProhibited", "nameprepProhibited is stringprep tables C.1.2 and C.2.2 to C.9.",
                ranges(prohibited))
    emit_ranges("nameprepRandAL", "nameprepRandAL is stringprep table D.1, RandALCat characters.",
                ranges(stringprep.in_table_d1))
    emit_ranges("nameprepL", "nameprepL is stringprep table D.2, LCat characters.",
                ranges(stringprep.in_table_d2))
    emit_map("nfkd32", "nfkd32 is each character's full Unicode 3.2 compatibility decomposition\n"
             "// (ucd_3_2_0.normalize('NFKD', c)), Hangul syllables aside.",
             [(ch, ucd_3_2_0.normalize("NFKD", ch)) for ch in CHARS
              if ord(ch) not in HANGUL and ucd_3_2_0.normalize("NFKD", ch) != ch])
    print("// combiningClass is the current database's nonzero canonical combining")
    print("// classes, which CPython's normalization orders and blocks by.")
    print("var combiningClass = map[rune]uint8{")
    for ch in CHARS:
        if unicodedata.combining(ch):
            print(f"\t0x{ord(ch):04x}: {unicodedata.combining(ch)},")
    print("}")
    print()
    print("// composePairs is the current database's canonical composition table.")
    print("var composePairs = map[[2]rune]rune{")
    for a, b, c in composition_pairs():
        print(f"\t{{0x{ord(a):04x}, 0x{ord(b):04x}}}: 0x{ord(c):04x},")
    print("}")


if __name__ == "__main__":
    sys.exit(main())
